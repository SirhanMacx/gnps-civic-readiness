<svelte:head><title>About the Seal — GNPS Civic Readiness</title></svelte:head>

<h1 class="font-display text-3xl text-primary mb-3">How the Seal works</h1>
<p class="font-serif text-lg text-muted mb-8 max-w-3xl">A transcript-and-diploma distinction earned across all four years of high school, awarded at graduation by the district once requirements are documented and verified.</p>

<section class="space-y-8">
  <div>
    <h2 class="font-display text-xl text-primary mb-2">Six points total — two from each column</h2>
    <p class="text-sm text-muted max-w-3xl">A student must earn 2 points from <strong>Civic Knowledge</strong>, 2 from <strong>Civic Participation</strong>, and 2 more from either column. Evidence accumulates from grade 9 onward — service hours done in 10th grade count toward a senior-year application.</p>
  </div>

  <div>
    <h2 class="font-display text-xl text-primary mb-2">Three kinds of evidence</h2>
    <ol class="list-decimal pl-6 space-y-3 max-w-3xl text-sm">
      <li><strong>Course &amp; Regents data</strong> — pulled directly from school records (Phase 2: live; Phase 1: counselor uploads CSV). Counts automatically.</li>
      <li><strong>Hours-based pathways</strong> — service-learning, work-based learning. You submit hours; we email your supervisor a one-click confirmation link. Once confirmed, hours count.</li>
      <li><strong>Project-based pathways</strong> — civic projects, research projects, Civics Capstone. You propose a topic; the Civic Readiness Committee approves before you do the work; you submit your finished project; the committee scores it against the NYSED rubric.</li>
    </ol>
  </div>

  <div>
    <h2 class="font-display text-xl text-primary mb-2">Reflections matter</h2>
    <p class="text-sm text-muted max-w-3xl">For service-learning and projects, NYSED requires a reflection that addresses the four civic-readiness domains: <strong>Knowledge</strong>, <strong>Skills</strong>, <strong>Mindsets</strong>, and <strong>Experiences</strong>. Reflections are reviewed by your counselor — they're how the Seal stays meaningful.</p>
  </div>

  <div>
    <h2 class="font-display text-xl text-primary mb-2">For families</h2>
    <p class="text-sm text-muted max-w-3xl">Phase 2 of this portal will let students and families log in and see live progress toward the Seal. For now, ask your counselor for a status check at any time.</p>
  </div>
</section>

