<h1 class="font-display text-4xl text-primary mb-3">How the Seal works</h1>
<p class="font-serif text-lg text-muted mb-2 max-w-3xl">The New York State Seal of Civic Readiness is a transcript-and-diploma distinction. It tells colleges, universities, and future employers that you've shown civic knowledge, civic skills, civic mindsets, and meaningful civic experiences across all four years of high school.</p>
<p class="font-serif text-base text-muted mb-10 max-w-3xl">It's awarded by Great Neck Public Schools at graduation. You don't apply once at the end — evidence accumulates from 9th grade onward. The earlier you start, the easier the senior year.</p>

<!-- The Six-Point Rule -->
<section class="mb-14 p-6 bg-surface rounded-lg border-l-4 border-secondary">
  <h2 class="font-display text-2xl text-primary mb-3">The six-point rule</h2>
  <p class="text-base text-ink mb-4 max-w-3xl">To earn the Seal, you need <strong>six points total</strong>:</p>
  <div class="grid sm:grid-cols-3 gap-4 text-sm">
    <div class="bg-white border border-border rounded p-4">
      <div class="font-display font-semibold text-primary text-base mb-1">≥ 2 points</div>
      <div class="text-muted">from Civic Knowledge column</div>
    </div>
    <div class="bg-white border border-border rounded p-4">
      <div class="font-display font-semibold text-primary text-base mb-1">≥ 2 points</div>
      <div class="text-muted">from Civic Participation column</div>
    </div>
    <div class="bg-white border border-border rounded p-4">
      <div class="font-display font-semibold text-primary text-base mb-1">+ 2 more</div>
      <div class="text-muted">from either column</div>
    </div>
  </div>
  <p class="text-sm text-muted mt-4 max-w-3xl"><em>You don't have to earn points in every category.</em> Pick a path that matches what you actually care about. The chart below is a menu, not a checklist.</p>
</section>

<!-- COLUMN 1 — KNOWLEDGE -->
<section class="mb-14">
  <div class="flex items-baseline gap-3 mb-2">
    <span class="font-display text-xs uppercase tracking-widest text-secondary font-semibold">Column 1</span>
    <h2 class="font-display text-3xl text-primary">Civic Knowledge</h2>
  </div>
  <p class="text-base text-muted mb-6 max-w-3xl">Demonstrated through your social studies coursework, Regents performance, and (optionally) a research project. <strong>Most students earn 2 of these points just by passing their required social studies classes.</strong> The rest is bonus.</p>

  <div class="space-y-4">
    <article class="border border-border rounded-lg p-5 bg-white">
      <div class="flex justify-between items-baseline mb-1">
        <h3 class="font-display text-lg text-primary">4 credits of social studies</h3>
        <span class="font-display font-semibold text-secondary">1 pt</span>
      </div>
      <p class="text-sm text-muted">Global History &amp; Geography I, Global History &amp; Geography II, US History &amp; Government, and Participation in Government / Economics. <strong>Required for any NYS diploma anyway.</strong> If you graduate, you've already earned this point.</p>
      <p class="text-xs text-muted mt-2 italic">Auto-counted from your transcript — nothing to submit.</p>
    </article>

    <article class="border border-border rounded-lg p-5 bg-white">
      <div class="flex justify-between items-baseline mb-1">
        <h3 class="font-display text-lg text-primary">Mastery on a Social Studies Regents</h3>
        <span class="font-display font-semibold text-secondary">1.5 pt · repeatable</span>
      </div>
      <p class="text-sm text-muted">Score <strong>85 or higher</strong> on the Global History &amp; Geography II Regents and/or the US History Regents. <em>Repeatable</em> — earning mastery on both gets you 3 points by itself.</p>
      <p class="text-xs text-muted mt-2 italic">Auto-counted from your Regents scores.</p>
    </article>

    <article class="border border-border rounded-lg p-5 bg-white">
      <div class="flex justify-between items-baseline mb-1">
        <h3 class="font-display text-lg text-primary">Proficiency on a Social Studies Regents</h3>
        <span class="font-display font-semibold text-secondary">1 pt · repeatable</span>
      </div>
      <p class="text-sm text-muted">Score <strong>65–84</strong> on Global II or US History Regents. Counts even with safety-net scores (55–64) if you have an IEP or 504 accommodation.</p>
      <p class="text-xs text-muted mt-2 italic">Auto-counted.</p>
    </article>

    <article class="border border-border rounded-lg p-5 bg-white">
      <div class="flex justify-between items-baseline mb-1">
        <h3 class="font-display text-lg text-primary">Advanced social studies course</h3>
        <span class="font-display font-semibold text-secondary">0.5 pt · repeatable</span>
      </div>
      <p class="text-sm text-muted">Pass an Honors, Pre-AP, AP, IB, or college/dual-enrollment social studies course. Examples at GNPS: AP US Government, AP World History, AP Human Geography, AP Macroeconomics, IB History.</p>
      <p class="text-xs text-muted mt-2 italic">Auto-counted from your transcript.</p>
    </article>

    <article class="border border-border rounded-lg p-5 bg-white">
      <div class="flex justify-between items-baseline mb-1">
        <h3 class="font-display text-lg text-primary">Civic-knowledge research project</h3>
        <span class="font-display font-semibold text-secondary">1 pt</span>
      </div>
      <p class="text-sm text-muted">A focused research paper on a civic, constitutional, historical, or policy question — using primary and secondary sources, evaluating bias, presenting findings. Proposed in advance to the Civic Readiness Committee, completed with a teacher's guidance, scored against the NYSED rubric.</p>
      <p class="text-xs text-muted mt-2 italic">You submit the topic via <a href="/submit/research" class="text-primary hover:underline">Submit Evidence → Research Project</a>.</p>
    </article>
  </div>
</section>

<!-- COLUMN 2 — PARTICIPATION -->
<section class="mb-14">
  <div class="flex items-baseline gap-3 mb-2">
    <span class="font-display text-xs uppercase tracking-widest text-secondary font-semibold">Column 2</span>
    <h2 class="font-display text-3xl text-primary">Civic Participation</h2>
  </div>
  <p class="text-base text-muted mb-6 max-w-3xl">Demonstrated through service hours, civic projects, work-based learning, and capstone projects. <strong>This is where you actually <em>do</em> civics</strong> — not just learn about it. Most students mix-and-match a few of these.</p>

  <div class="space-y-4">
    <article class="border border-border rounded-lg p-5 bg-white">
      <div class="flex justify-between items-baseline mb-1">
        <h3 class="font-display text-lg text-primary">High School Civic Project</h3>
        <span class="font-display font-semibold text-secondary">1.5 pt · max 2× (3pt cap)</span>
      </div>
      <p class="text-sm text-muted">A short project on a civic issue or policy — analyze data, evaluate two policies, recommend strategies, communicate findings. Often paired with class assignments. <strong>You can earn this twice in grades 9–12.</strong></p>
      <p class="text-xs text-muted mt-2 italic">Topic pre-approved by the Civic Readiness Committee. Submit via <a href="/submit/civic-project" class="text-primary hover:underline">Submit Evidence → HS Civic Project</a>.</p>
    </article>

    <article class="border border-border rounded-lg p-5 bg-white">
      <div class="flex justify-between items-baseline mb-1">
        <h3 class="font-display text-lg text-primary">Service-Learning Project</h3>
        <span class="font-display font-semibold text-secondary">1 pt · repeatable</span>
      </div>
      <p class="text-sm text-muted"><strong>25+ hours</strong> of community service connected to learning, plus a reflection essay. NYSED defines service-learning as five stages: investigation, preparation, action (direct service / indirect service / advocacy), <strong>reflection</strong>, and demonstration. The reflection is what earns the point — not just the hours.</p>
      <p class="text-xs text-muted mt-2 italic">Submit hours via <a href="/submit/service" class="text-primary hover:underline">Submit Evidence → Service-Learning Hours</a>. Your supervisor receives a one-click confirmation email.</p>
    </article>

    <article class="border border-border rounded-lg p-5 bg-white">
      <div class="flex justify-between items-baseline mb-1">
        <h3 class="font-display text-lg text-primary">Civic-engagement elective</h3>
        <span class="font-display font-semibold text-secondary">0.5 pt · repeatable</span>
      </div>
      <p class="text-sm text-muted">Pass an elective course that promotes civic engagement (the Civic Readiness Committee maintains the list — examples include Constitutional Law, Mock Trial, Model UN, Journalism, World Religions, AP Human Geography). <strong>Plus</strong> submit a short application-of-knowledge essay tying what you learned to civic action.</p>
      <p class="text-xs text-muted mt-2 italic">Auto-counted from your grade; essay submitted via <a href="/submit/civic-elective" class="text-primary hover:underline">Submit Evidence → Civic-Engagement Elective Essay</a>.</p>
    </article>

    <article class="border border-border rounded-lg p-5 bg-white">
      <div class="flex justify-between items-baseline mb-1">
        <h3 class="font-display text-lg text-primary">Middle School Capstone Project</h3>
        <span class="font-display font-semibold text-secondary">1 pt · grades 7–8 only</span>
      </div>
      <p class="text-sm text-muted">A capstone project completed in 7th or 8th grade. Typical structure: identify a local/state/national/global issue, apply civic knowledge and skills to it, present to the Middle School Capstone Committee.</p>
      <p class="text-xs text-muted mt-2 italic">If you completed one in middle school, you can back-enter it during 9th-grade onboarding with a teacher's signoff. Counts retroactively toward your seal.</p>
    </article>

    <article class="border border-border rounded-lg p-5 bg-white">
      <div class="flex justify-between items-baseline mb-1">
        <h3 class="font-display text-lg text-primary">Extra-curricular / Work-Based Learning</h3>
        <span class="font-display font-semibold text-secondary">0.5 pt · repeatable</span>
      </div>
      <p class="text-sm text-muted"><strong>40+ hours</strong> of participation in a civic-engagement extracurricular (Model UN, Student Government, Mock Trial, Debate, Journalism, etc.) <em>or</em> a work-based learning experience that promotes civic action. Plus an application-of-knowledge essay. Hours can accumulate over all four years.</p>
      <p class="text-xs text-muted mt-2 italic">Submit via <a href="/submit/wbl" class="text-primary hover:underline">Submit Evidence → Extra-curricular / Work-Based Learning</a>.</p>
    </article>

    <article class="border-2 border-secondary rounded-lg p-5 bg-orange-50">
      <div class="flex justify-between items-baseline mb-1">
        <h3 class="font-display text-xl text-primary">Civics Capstone Project</h3>
        <span class="font-display font-bold text-secondary text-lg">4 pts</span>
      </div>
      <p class="text-sm text-ink mb-3">The single largest pathway. <strong>One capstone alone almost earns the entire participation column</strong>, plus the 2 you've likely got from coursework. NYSED requires four essential elements:</p>
      <ol class="list-decimal pl-6 text-sm space-y-1 text-ink">
        <li><strong>Identify an issue</strong> — local, state, national, or global</li>
        <li><strong>Apply civic knowledge, skills, actions, and mindsets</strong> to that issue</li>
        <li><strong>Engage in a civic experience</strong> based on the issue to influence positive change in your community</li>
        <li><strong>Present</strong> the project to the school's Civic Readiness Committee</li>
      </ol>
      <p class="text-xs text-muted mt-3 italic">Topic pre-approved by SCRC. Final work scored against NYSED Appendix P rubric. Often a year-long undertaking. Submit via <a href="/submit/capstone" class="text-primary hover:underline">Submit Evidence → Civics Capstone Project</a>.</p>
    </article>
  </div>
</section>

<!-- THE FOUR DOMAINS -->
<section class="mb-14">
  <h2 class="font-display text-2xl text-primary mb-3">The four civic-readiness domains</h2>
  <p class="text-base text-muted mb-5 max-w-3xl">Every project and reflection should address NYSED's four civic-readiness domains. They're how the state defines what "civic readiness" means.</p>
  <div class="grid sm:grid-cols-2 gap-4 text-sm">
    <div class="border border-border rounded p-4">
      <div class="font-display font-semibold text-primary mb-1">Civic Knowledge</div>
      <div class="text-muted">Government structure, history, geography, economics, current events. The "what."</div>
    </div>
    <div class="border border-border rounded p-4">
      <div class="font-display font-semibold text-primary mb-1">Civic Skills &amp; Actions</div>
      <div class="text-muted">Critical thinking, media literacy, debate, persuasive communication, organizing. The "how."</div>
    </div>
    <div class="border border-border rounded p-4">
      <div class="font-display font-semibold text-primary mb-1">Civic Mindsets</div>
      <div class="text-muted">Empathy, equity, respect for differing viewpoints, commitment to common good. The "why."</div>
    </div>
    <div class="border border-border rounded p-4">
      <div class="font-display font-semibold text-primary mb-1">Civic Experiences</div>
      <div class="text-muted">Voting, volunteering, advocacy, working with elected officials, community organizing. The "doing."</div>
    </div>
  </div>
</section>

<!-- HOW EVIDENCE GETS VERIFIED -->
<section class="mb-14">
  <h2 class="font-display text-2xl text-primary mb-3">How evidence gets verified</h2>
  <p class="text-base text-muted mb-5 max-w-3xl">There are three kinds of evidence in this system. Each has a different verification path, by design — fraud risk lives in different places for each.</p>

  <div class="space-y-4">
    <div class="border-l-4 border-primary pl-5 py-2">
      <h3 class="font-display font-semibold text-primary">1. Course &amp; Regents data → auto-counts</h3>
      <p class="text-sm text-muted">Pulled directly from school records. No submission needed. If you passed a class or scored on a Regents, the system already knows.</p>
    </div>
    <div class="border-l-4 border-primary pl-5 py-2">
      <h3 class="font-display font-semibold text-primary">2. Hours-based pathways → supervisor email confirmation</h3>
      <p class="text-sm text-muted">For service-learning and work-based learning, you submit your hours and your supervisor's email. The portal sends them a one-click "confirm hours" link. They click confirm; you can keep building toward the threshold. No supervisor account needed — it works like a job-reference email.</p>
    </div>
    <div class="border-l-4 border-primary pl-5 py-2">
      <h3 class="font-display font-semibold text-primary">3. Project-based pathways → SCRC committee review</h3>
      <p class="text-sm text-muted">For research, civic projects, and the capstone, the Civic Readiness Committee reviews your topic <strong>before</strong> you do the work, then scores the finished project against NYSED rubrics. Counselors confirm the final point award.</p>
    </div>
  </div>
</section>

<!-- FOR FAMILIES -->
<section class="mb-14 bg-surface p-6 rounded-lg">
  <h2 class="font-display text-2xl text-primary mb-3">For families</h2>
  <p class="text-base text-muted mb-3 max-w-3xl">The Seal isn't a transcript line item that adds work for the sake of work. It's a way for your student to be recognized — to colleges, to scholarship committees, to future employers — for what they're already doing or interested in doing as engaged citizens.</p>
  <p class="text-base text-muted mb-3 max-w-3xl"><strong>Things you can do to help:</strong></p>
  <ul class="list-disc pl-6 text-sm text-muted space-y-1.5">
    <li>Encourage them to start submitting evidence in 9th or 10th grade — senior-year scrambles lose evidence</li>
    <li>If they volunteer somewhere, ask their supervisor in advance whether they'd be willing to receive a confirmation email later</li>
    <li>Ask their counselor for a status check at any time</li>
    <li>For seniors planning a Civics Capstone Project, support the year-long timeline (it's a real undertaking)</li>
  </ul>
  <p class="text-sm text-muted mt-4">Phase 2 of this portal will let students and families log in and see live progress. For now, your student's counselor has the most current view.</p>
</section>

<!-- TIMING -->
<section class="mb-14">
  <h2 class="font-display text-2xl text-primary mb-3">Timing — when can I start?</h2>
  <p class="text-base text-muted mb-3 max-w-3xl"><strong>Now.</strong> Evidence accumulates from grade 9 onward. Service hours done in 10th grade count toward your senior-year application. There's no point in waiting.</p>
  <p class="text-sm text-muted max-w-3xl">If you completed a middle school capstone project in grades 7 or 8, that retroactively counts (1 pt) — talk to your counselor at the start of 9th grade to back-enter it.</p>
</section>

